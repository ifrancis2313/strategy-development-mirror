"""The frozen-copy mechanism itself: physically copies a dependency
closure's source files into a destination directory, rewriting every
`from testing.X import Y` into a relative import, so the result has zero
live import back to `testing/`'s ongoing code -- once written, this
directory never changes even if `testing/` does.

Relative (not absolute-to-some-new-package-name) imports are used
deliberately: the frozen snapshot doesn't have to know or care what it
ends up nested under (`graduated/vrp_harvester/v3_.../`, a Shadow-wing
inbox, a copy pasted into a Pipeline repo later) -- it's just a valid,
self-contained Python package tree wherever it lands.
"""

from __future__ import annotations

import ast
import hashlib
import re
from pathlib import Path

from testing.graduation.closure import TESTING_ROOT_PACKAGE, ModuleSource

_IMPORT_LINE = re.compile(
    r"^(?P<indent>[ \t]*)from[ \t]+(?P<module>testing(?:\.[A-Za-z_][A-Za-z0-9_]*)+)[ \t]+import[ \t]+(?P<rest>.+)$",
    re.MULTILINE,
)


def relative_import(from_module: str, to_module: str) -> str:
    """Computes the dotted string (with its leading dots) for a Python
    relative import that lets a module at `from_module` (a
    frozen-snapshot-relative dotted path, e.g.
    'strategies.vrp_harvester.trade_selector') reach `to_module`
    ('engine.leg') -- without either module needing to know what package
    name the frozen snapshot is nested under at import time.
    """
    from_package = from_module.split(".")[:-1]
    to_parts = to_module.split(".")

    common = 0
    while common < len(from_package) and common < len(to_parts) - 1 and from_package[common] == to_parts[common]:
        common += 1

    up_levels = len(from_package) - common
    dots = "." * (up_levels + 1)
    remainder = to_parts[common:]
    return dots + ".".join(remainder)


def _rewrite_imports(source: str, module_relative_dotted: str) -> str:
    def _replace(match: re.Match[str]) -> str:
        absolute_module = match.group("module")
        target_relative = absolute_module[len(TESTING_ROOT_PACKAGE) + 1 :]
        rel_import = relative_import(module_relative_dotted, target_relative)
        return f'{match.group("indent")}from {rel_import} import {match.group("rest")}'

    return _IMPORT_LINE.sub(_replace, source)


def write_snapshot(closure: dict[str, ModuleSource], destination: Path) -> tuple[str, ...]:
    """Physically copies every module in `closure` into `destination`,
    rewriting its `testing.*` imports to relative imports. Returns the
    sorted tuple of relative dotted module paths written, for the
    manifest's audit trail.
    """
    destination.mkdir(parents=True, exist_ok=True)
    package_dirs: set[Path] = {destination}

    for module in closure.values():
        source = module.source_path.read_text()
        rewritten = _rewrite_imports(source, module.relative_dotted)

        dest_path = (destination / Path(*module.relative_dotted.split("."))).with_suffix(".py")
        dest_path.parent.mkdir(parents=True, exist_ok=True)
        dest_path.write_text(rewritten)

        parent = dest_path.parent
        while parent != destination and parent not in package_dirs:
            package_dirs.add(parent)
            parent = parent.parent

    for package_dir in package_dirs:
        init_file = package_dir / "__init__.py"
        if not init_file.exists():
            init_file.write_text(
                '"""Frozen graduation snapshot -- generated by testing/graduation. '
                'Do not edit by hand; it will not affect anything already graduated '
                'and will be silently out of sync with its own manifest."""\n'
            )

    return tuple(sorted(module.relative_dotted for module in closure.values()))


def verify_no_testing_imports(destination: Path) -> None:
    """Hard gate, run at the end of every graduation: AST-parses every
    `.py` file under `destination` and raises if any absolute `testing.*`
    import survived the rewrite. This is what actually enforces the
    zero-live-dependency guarantee -- not just the rewrite regex's own
    coverage, which only handles the single-line import shape used
    everywhere in `testing/` today. If a future module ever uses a
    multi-line/parenthesized import, this catches the miss instead of
    silently shipping a leaky snapshot.
    """
    for path in sorted(destination.rglob("*.py")):
        tree = ast.parse(path.read_text(), filename=str(path))
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and node.module and (
                node.module == TESTING_ROOT_PACKAGE or node.module.startswith(TESTING_ROOT_PACKAGE + ".")
            ):
                raise RuntimeError(
                    f"{path}: still imports {node.module!r} after snapshotting -- "
                    "the frozen-copy rewrite missed this import"
                )
            if isinstance(node, ast.Import):
                for alias in node.names:
                    if alias.name == TESTING_ROOT_PACKAGE or alias.name.startswith(TESTING_ROOT_PACKAGE + "."):
                        raise RuntimeError(
                            f"{path}: still imports {alias.name!r} after snapshotting -- "
                            "the frozen-copy rewrite missed this import"
                        )


def hash_snapshot(destination: Path) -> str:
    """SHA-256 over every copied module's rewritten content, sorted by
    relative path -- an integrity fingerprint recorded in the manifest so
    a later audit can detect whether a snapshot's files were altered after
    the fact, independent of the manifest's own claims about itself.
    """
    hasher = hashlib.sha256()
    for path in sorted(destination.rglob("*.py")):
        hasher.update(path.relative_to(destination).as_posix().encode())
        hasher.update(path.read_bytes())
    return hasher.hexdigest()
